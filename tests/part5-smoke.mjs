import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = path => readFileSync(resolve(root, path), "utf8");
const required = ["part5.js","_headers","PART5-LAUNCH-CHECKLIST.md","payment-return.html","functions/api/[[path]].js","src/worker.js","wrangler.toml"];
for (const path of required) assert.ok(existsSync(resolve(root,path)), "required file exists: " + path);
const scriptOrder = (html,first,second) => assert.ok(html.indexOf(first)>=0 && html.indexOf(second)>html.indexOf(first), first+" must load before "+second);
scriptOrder(read("index.html"),"part5.js","app.js");
scriptOrder(read("service.html"),"part5.js","part2.js");
scriptOrder(read("website-builder.html"),"part5.js","part2.js");
scriptOrder(read("signup.html"),"part5.js","part3.js");
scriptOrder(read("login.html"),"part5.js","part3.js");
scriptOrder(read("dashboard.html"),"part5.js","part3.js");
const frontend=read("part5.js");
for(const route of ["/enquiry","/signup","/login","/logout","/user/me","/services","/orders","/payments/create"]) assert.ok(frontend.includes('"' + route + '"'),"frontend connects to "+route);
assert.ok(frontend.includes("/upload"),"frontend supports private document uploads");
assert.ok(frontend.includes("paymentSessionId"),"frontend uses the gateway session created by the server");
assert.ok(!frontend.includes("localStorage.setItem")&&!frontend.includes("sessionStorage.setItem"),"customer records are not stored in browser storage");
const worker=read("src/worker.js");
assert.ok(worker.includes("x-webhook-signature")&&worker.includes("x-webhook-timestamp"),"Cashfree webhook signature headers are verified");
assert.ok(worker.includes("R2_BUCKET.put"),"uploads use the R2 binding");
assert.ok(worker.includes(".prepare("),"database queries use D1 prepared statements");
assert.ok(worker.includes("HttpOnly")&&worker.includes("SameSite=Lax"),"session cookie has secure session attributes");
const headers=read("_headers");
for(const header of ["Content-Security-Policy:","X-Content-Type-Options: nosniff","X-Frame-Options: DENY","Referrer-Policy:","Permissions-Policy:"]) assert.ok(headers.includes(header),"security header configured: "+header);
assert.ok(read("wrangler.toml").includes("REPLACE_WITH_CLOUDFLARE_D1_DATABASE_ID"),"production D1 placeholder remains visible to reviewers until configured");
const checklist=read("PART5-LAUNCH-CHECKLIST.md").toLowerCase();
for(const blocker of ["d1 database","email verification","password reset","rate limits","malware scanning","cashfree production"]) assert.ok(checklist.includes(blocker),"launch checklist tracks "+blocker);
console.log("GOAXIS Part 5 static smoke checks passed.");
console.log("This is not a live browser, Cloudflare D1/R2 or payment-gateway end-to-end test. Complete PART5-LAUNCH-CHECKLIST.md before launch.");
